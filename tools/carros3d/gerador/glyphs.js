export function glyphStrokes(str, { h = 0.2, spacing = 0.4 } = {}) {
  const s = h / 6;
  const adv = 4 + spacing * 4;
  const chars = [...str.toUpperCase()];
  const total = chars.length * adv - spacing * 4;
  const out = [];
  chars.forEach((ch, i) => {
    const g = G[ch];
    if (!g) return;
    const ox = i * adv - total / 2;
    for (const [p, q] of g) out.push([[(p[0] + ox) * s, (p[1] - 3) * s], [(q[0] + ox) * s, (q[1] - 3) * s]]);
  });
  return out;
}
